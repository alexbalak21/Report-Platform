"""Safe, read-only access to uploaded workbooks.

Everything user-controlled is validated before openpyxl sees it: size, zip structure, a
zip-bomb limit on the uncompressed size, no macros. Values are read with `data_only=True`
(cached results of formulas); a second formula-aware pass flags formulas whose result was
never cached (typical for files generated by scripts), instead of silently importing blanks.
"""

from __future__ import annotations

import io
import re
import unicodedata
import zipfile
from collections.abc import Iterator
from dataclasses import dataclass
from datetime import date, datetime, time
from typing import Any

from openpyxl import load_workbook
from rp_shared.errors import ValidationFailed

from .config import IngestionConfig


class InvalidWorkbook(ValidationFailed):
    code = "INVALID_WORKBOOK"


class FileTooLarge(ValidationFailed):
    status = 413
    code = "FILE_TOO_LARGE"


# ---------------------------------------------------------------------------
# Names
# ---------------------------------------------------------------------------
def norm_header(value: Any) -> str:
    """Same key for '  Nom Entreprise-Client ', 'nom_entreprise_client', 'Nom entreprise client'."""
    s = unicodedata.normalize("NFKD", str(value if value is not None else ""))
    s = "".join(c for c in s if not unicodedata.combining(c)).lower()
    return re.sub(r"[^a-z0-9]+", " ", s).strip()


def snake_key(value: Any) -> str:
    """Placeholder-safe key from a header: 'Nom entreprise client' -> nom_entreprise_client."""
    key = norm_header(value).replace(" ", "_")
    if not key:
        return "col"
    if not key[0].isalpha():
        key = "c_" + key
    return key[:63]


def lookup_key(value: Any) -> Any:
    """Comparison key for lookups: 1, 1.0 and '1 ' match; text is case-insensitive."""
    if value is None:
        return None
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    s = str(value).strip().casefold()
    return s or None


def jsonable(value: Any) -> Any:
    if isinstance(value, (datetime, date, time)):
        return value.isoformat()
    if value is None or isinstance(value, (bool, int, float, str)):
        return value
    return str(value)


# ---------------------------------------------------------------------------
# Validation + opening
# ---------------------------------------------------------------------------
def check_xlsx(data: bytes, cfg: IngestionConfig) -> None:
    if len(data) > cfg.max_upload_bytes:
        raise FileTooLarge(f"File is larger than {cfg.max_upload_bytes // (1024 * 1024)} MB")
    if not data.startswith(b"PK\x03\x04"):
        raise InvalidWorkbook("Not an .xlsx file (expected a zip container)")
    try:
        zf = zipfile.ZipFile(io.BytesIO(data))
        infos = zf.infolist()
    except zipfile.BadZipFile as exc:
        raise InvalidWorkbook("Corrupt .xlsx file") from exc
    names = {i.filename for i in infos}
    if "[Content_Types].xml" not in names or "xl/workbook.xml" not in names:
        raise InvalidWorkbook("Not an Excel workbook (missing workbook parts)")
    if any("vbaProject" in n for n in names):
        raise InvalidWorkbook("Macro-enabled workbooks are not accepted")
    if len(infos) > 5000:
        raise InvalidWorkbook("Workbook has too many internal parts")
    total = 0
    for info in infos:
        if info.filename.startswith(("/", "..")) or ".." in info.filename.split("/"):
            raise InvalidWorkbook("Workbook contains unsafe paths")
        total += info.file_size
        if info.file_size > 1_000_000 and info.file_size / max(info.compress_size, 1) > 1000:
            raise InvalidWorkbook("Workbook looks like a decompression bomb")
    if total > cfg.max_uncompressed_bytes:
        raise InvalidWorkbook("Workbook is too large once unpacked")


def open_workbook(data: bytes, *, data_only: bool = True):
    try:
        return load_workbook(io.BytesIO(data), read_only=True, data_only=data_only)
    except Exception as exc:  # openpyxl raises a zoo of exception types on bad input
        raise InvalidWorkbook("Could not read the workbook") from exc


def sheet_names(data: bytes, cfg: IngestionConfig) -> list[str]:
    wb = open_workbook(data)
    try:
        names = list(wb.sheetnames)
    finally:
        wb.close()
    if len(names) > cfg.max_sheets:
        raise InvalidWorkbook(f"Workbook has more than {cfg.max_sheets} sheets")
    return names


def find_sheet(names: list[str], wanted: str | None) -> str | None:
    """Sheet by (normalised) name; the first sheet when no name is wanted."""
    if wanted is None:
        return names[0] if names else None
    target = norm_header(wanted)
    return next((n for n in names if norm_header(n) == target), None)


# ---------------------------------------------------------------------------
# Headers
# ---------------------------------------------------------------------------
@dataclass
class Headers:
    raw: list[Any]
    index: dict[str, int]  # normalised header -> column index (first occurrence)
    duplicates: set[str]

    @classmethod
    def from_row(cls, row: tuple | list) -> Headers:
        raw = list(row)
        while raw and (raw[-1] is None or str(raw[-1]).strip() == ""):
            raw.pop()
        index: dict[str, int] = {}
        dups: set[str] = set()
        for i, h in enumerate(raw):
            key = norm_header(h)
            if not key:
                continue
            if key in index:
                dups.add(key)
            else:
                index[key] = i
        return cls(raw, index, dups)

    def find(self, name: str) -> int | None:
        return self.index.get(norm_header(name))

    def labels(self) -> list[str]:
        return [str(h).strip() for h in self.raw if h is not None and str(h).strip()]


def read_headers(data: bytes, sheet: str, header_row: int = 1) -> Headers:
    wb = open_workbook(data)
    try:
        ws = wb[sheet]
        for row in ws.iter_rows(min_row=header_row, max_row=header_row, values_only=True):
            return Headers.from_row(row)
        return Headers([], {}, set())
    finally:
        wb.close()


# ---------------------------------------------------------------------------
# Rows
# ---------------------------------------------------------------------------
def iter_sheet_rows(
    data: bytes,
    sheet: str,
    first_row: int,
    cfg: IngestionConfig,
    *,
    check_formulas: bool = False,
) -> Iterator[tuple[int, tuple, set[int]]]:
    """Yield (excel_row_number, values, columns_whose_formula_has_no_cached_value)."""
    wb_v = open_workbook(data, data_only=True)
    wb_f = open_workbook(data, data_only=False) if check_formulas else None
    try:
        rows_f = (
            wb_f[sheet].iter_rows(min_row=first_row, values_only=True) if wb_f is not None else None
        )
        for n, v_row in enumerate(
            wb_v[sheet].iter_rows(min_row=first_row, values_only=True), start=first_row
        ):
            f_row = next(rows_f, ()) if rows_f is not None else ()
            if n - first_row >= cfg.max_rows_per_sheet:
                raise InvalidWorkbook(
                    f"Sheet '{sheet}' has more than {cfg.max_rows_per_sheet} rows"
                )
            missing = {
                i
                for i, v in enumerate(v_row)
                if v is None
                and i < len(f_row)
                and isinstance(f_row[i], str)
                and f_row[i][:1] == "="
            }
            yield n, v_row, missing
    finally:
        wb_v.close()
        if wb_f is not None:
            wb_f.close()


def build_lookup(
    data: bytes,
    sheet: str,
    key_column: str,
    value_column: str,
    cfg: IngestionConfig,
    header_row: int = 1,
) -> tuple[dict[Any, Any], set[Any]]:
    """{normalised key: value} for a reference sheet, plus keys that appear more than once."""
    headers = read_headers(data, sheet, header_row)
    ki, vi = headers.find(key_column), headers.find(value_column)
    if ki is None or vi is None:
        missing = key_column if ki is None else value_column
        raise InvalidWorkbook(f"Lookup sheet '{sheet}' has no column '{missing}'")
    table: dict[Any, Any] = {}
    dups: set[Any] = set()
    for _n, row, _m in iter_sheet_rows(data, sheet, header_row + 1, cfg):
        key = lookup_key(row[ki] if ki < len(row) else None)
        if key is None:
            continue
        if key in table:
            dups.add(key)
            continue  # first match wins, but the duplicate is reported
        table[key] = row[vi] if vi < len(row) else None
    return table, dups


# ---------------------------------------------------------------------------
# Preview helpers
# ---------------------------------------------------------------------------
def guess_type(values: list[Any]) -> str:
    vals = [v for v in values if v is not None and str(v).strip() != ""]
    if not vals:
        return "string"
    if all(isinstance(v, bool) for v in vals):
        return "boolean"
    if all(isinstance(v, (datetime, date)) and not isinstance(v, bool) for v in vals):
        has_time = any(isinstance(v, datetime) and v.time() != time(0) for v in vals)
        return "datetime" if has_time else "date"
    nums = [v for v in vals if isinstance(v, (int, float)) and not isinstance(v, bool)]
    if len(nums) == len(vals):
        if all(isinstance(v, int) or float(v).is_integer() for v in nums):
            return "integer"
        return "number"
    return "string"


def preview_sheet(
    data: bytes, sheet: str, cfg: IngestionConfig, header_row: int = 1
) -> dict[str, Any]:
    headers = read_headers(data, sheet, header_row)
    width = len(headers.raw)
    rows: list[list[Any]] = []
    cols: list[list[Any]] = [[] for _ in range(width)]
    for _n, row, _m in iter_sheet_rows(data, sheet, header_row + 1, cfg):
        padded = [row[i] if i < len(row) else None for i in range(width)]
        if all(v is None or str(v).strip() == "" for v in padded):
            continue
        if len(rows) < cfg.preview_rows:
            rows.append([jsonable(v) for v in padded])
        for i, v in enumerate(padded):
            if len(cols[i]) < 200:
                cols[i].append(v)
        if len(rows) >= cfg.preview_rows and all(len(c) >= 200 for c in cols):
            break
    suggested = []
    used: set[str] = set()
    for i, h in enumerate(headers.raw):
        if h is None or str(h).strip() == "":
            continue
        target = snake_key(h)
        base, n = target, 2
        while target in used:
            target = f"{base[:60]}_{n}"
            n += 1
        used.add(target)
        suggested.append(
            {
                "source": str(h).strip(),
                "target": target,
                "type": guess_type(cols[i]),
            }
        )
    return {
        "name": sheet,
        "header_row": header_row,
        "headers": headers.labels(),
        "duplicate_headers": sorted(headers.duplicates),
        "rows": rows,
        "suggested_columns": suggested,
    }
